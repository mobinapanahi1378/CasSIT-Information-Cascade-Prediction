# --------------------------------------------------
# 1. Structural-Influence-Aware Temporal Attention
# --------------------------------------------------
class StructuralInfluenceAwareTemporalAttention(nn.Module):
    """
    Computes temporal attention by jointly considering
    temporal representations and structural-influence
    representations of cascade subgraphs.

    Args:
        h_seq: (B, T, H)
            Temporal representations generated by BiGRU.

        u_seq: (B, T, U)
            Structural-influence representations of cascade
            subgraphs, obtained from the autoencoder.

    Returns:
        H: (B, H)
            Attention-weighted temporal representation of the cascade.

        alpha: (B, T)
            Attention weights assigned to cascade time intervals.
    """

    def __init__(self, h_dim, u_dim, att_dim=128):
        super().__init__()
        self.W_h = nn.Linear(h_dim, att_dim)
        self.W_u = nn.Linear(u_dim, att_dim)
        self.v = nn.Linear(att_dim, 1)

    def forward(self, h_seq, u_seq):
        # Input temporal and structural-influence representations
        # h_seq: (B, T, H)
        # u_seq: (B, T, U)

        # Project both representations into a shared attention space
        h_proj = self.W_h(h_seq)          # (B, T, att)
        u_proj = self.W_u(u_seq)          # (B, T, att)

        # Jointly model temporal and structural-influence information
        e = torch.tanh(h_proj + u_proj)   # (B, T, att)

        # Compute an attention score for each time interval
        scores = self.v(e).squeeze(-1)    # (B, T)

        # Normalize attention scores across time intervals
        alpha = torch.softmax(scores, dim=-1)  # (B, T)

        # Aggregate temporal representations using attention weights
        H = torch.bmm(alpha.unsqueeze(1), h_seq).squeeze(1)  # (B, H)

        return H, alpha


# --------------------------------------------------
# 2. Structural-Influence-Temporal Fusion Gate
# --------------------------------------------------
class StructuralInfluenceTemporalFusionGate(nn.Module):
    """
    Adaptively fuses the global structural-influence
    representation with the attention-weighted temporal
    representation of the cascade.

    Args:
        H: (B, H)
            Attention-weighted temporal representation.

        u_glob: (B, U)
            Global structural-influence representation,
            obtained by averaging subgraph-level representations.

    Returns:
        z_fusion: (B, max(H, U))
            Fused structural-influence-temporal representation.
    """

    def __init__(self, h_dim, u_dim):
        super().__init__()
        self.fc = nn.Linear(h_dim + u_dim, 1)

        # Project both representations into a common dimensional space
        out_dim = max(h_dim, u_dim)
        self.proj_h = nn.Linear(h_dim, out_dim)
        self.proj_u = nn.Linear(u_dim, out_dim)
        self.out_dim = out_dim

    def forward(self, H, u_glob):
        # Input representations
        # H: (B, H)
        # u_glob: (B, U)

        # Compute an adaptive fusion gate
        beta = torch.sigmoid(self.fc(torch.cat([H, u_glob], dim=-1)))  # (B, 1)

        # Map both representations into the shared output space
        H_proj = self.proj_h(H)          # (B, D)
        u_proj = self.proj_u(u_glob)     # (B, D)

        # Adaptively combine structural-influence and temporal information
        z_fusion = beta * u_proj + (1.0 - beta) * H_proj   # (B, D)

        return z_fusion


# --------------------------------------------------
# 3. CasSIT: Structural-Influence-Aware Cascade Prediction Model
# --------------------------------------------------
class CasSIT(nn.Module):
    def __init__(self, increase_node, feat_in, squence_length, input_dim,
                 n_time_interval, emb_dim, z_dim):
        super(CasSIT, self).__init__()
        self.squence_length = squence_length
        self.input_dim = input_dim
        self.n_time_interval = n_time_interval
        self.emb_dim = emb_dim
        self.z_dim = z_dim
        self.dens_hiddensize1 = 128
        self.dens_hiddensize2 = 64
        self.feat_in = feat_in
        self.increase_node = increase_node
        self.feat_hidden = 50
        self.feat_out = 64
        self.rnn_hidden = 128
        self.dropout = 0.2
        self.num_layers = 2
        self.n_steps = 100
        self.pad_node = self.n_steps % self.increase_node

        self._set_layers()
        self._reset_params()

    def _reset_params(self):
        # Initialize all trainable model parameters
        for p in self.parameters():
            if p.requires_grad:
                if len(p.shape) > 1:
                    init.kaiming_uniform_(p)
                else:
                    stdv = 1. / math.sqrt(p.shape[0])
                    init.uniform_(p, a=-stdv, b=stdv)

    # Compute the Mean Squared Logarithmic Error (MSLE)
    def MeanSquaredLogarithmicError(self, pred, truth):
        first_log = torch.log2(torch.clamp(pred, 1e-7, None) + 1.0)
        second_log = torch.log2(torch.clamp(truth, 1e-7, None) + 1.0)
        return torch.nn.functional.mse_loss(first_log, second_log)

    def _set_layers(self):

        # Global user representation learning using an autoencoder
        # and an auxiliary user classification task.
        self.emb_layer = GlobalEmbing(
            squence_length=self.squence_length,
            input_dim=self.input_dim,
            emb_dim=self.emb_dim,
            z_dim=self.z_dim
        )

        # Extract local structural representations from cascade subgraphs
        # using a bidirectional graph convolutional network.
        self.bigcn = BiGCN(
            input_features=self.feat_in,
            hidden_features=self.feat_hidden,
            output_features=self.feat_out
        )

        # Learn joint structural-influence representations by combining
        # local graph structure features and global user embeddings.
        self.ae = AE(
            input_dim=self.feat_out + self.z_dim,
            h_dim=96,
            z_dim=self.z_dim
        )

        # Model the temporal evolution of cascade subgraphs
        # using a bidirectional GRU.
        # The input consists of structural-influence representations
        # concatenated with temporal features.
        self.biGRU = nn.GRU(
            input_size=self.z_dim + 1,
            hidden_size=self.rnn_hidden,
            bidirectional=True,
            batch_first=True,
            num_layers=self.num_layers,
            dropout=self.dropout
        )

        # Additional structural-influence-aware temporal attention module
        self.structural_influence_temporal_attention = StructuralInfluenceAwareTemporalAttention(
            h_dim=self.rnn_hidden * 2,
            u_dim=self.z_dim,
            att_dim=128
        )

        # Additional adaptive structural-influence-temporal fusion gate
        self.structural_influence_temporal_fusion_gate = StructuralInfluenceTemporalFusionGate(
            h_dim=self.rnn_hidden * 2,
            u_dim=self.z_dim
        )

        # Final multilayer perceptron for cascade size prediction
        self.mlp2 = MPL_Net(
            dens_inputsize=max(self.rnn_hidden * 2, self.z_dim),
            dens_outputsize=1,
            dens_dropout=self.dropout,
            dens_hiddensize1=self.dens_hiddensize1,
            dens_hiddensize2=self.dens_hiddensize2
        )

    def forward(self, batch_x, batch_l, batch_global_x, batch_y,
                batch_label, batch_time_interval, batch_rnn_index,
                batch_time_serise):

        # --------------------------------------------------
        # 1. Global User Representation Learning
        # --------------------------------------------------
        # Learn global user embeddings and compute the associated
        # autoencoder and auxiliary classification losses.
        total_loss_global, total_classfier_loss, total_classfier_acc, batch_z = \
            self.emb_layer(batch_global_x, batch_label)

        # Separate the global autoencoder loss from the classification loss
        # total_loss_global = total_vae_loss_global + total_classfier_loss
        total_vae_loss_global = total_loss_global - total_classfier_loss

        # --------------------------------------------------
        # 2. Subgraph-Level User Representation Aggregation
        # --------------------------------------------------
        # Aggregate node-level user embeddings into subgraph-level
        # representations according to the number of newly activated nodes.
        if self.increase_node > 1:

            # Original node-level embeddings: (B, n_steps, z_dim)
            batch_temp_z = torch.reshape(
                batch_z[:, :(self.n_steps // self.increase_node) * self.increase_node],
                [batch_z.shape[0], -1, self.increase_node, batch_z.shape[2]]
            )  # (B, T', increase_node, z_dim)

            # Aggregate node embeddings within each subgraph
            batch_temp_z = torch.sum(batch_temp_z, dim=2, keepdim=False)  # (B, T', z_dim)

            # Handle the remaining nodes that do not form a complete subgraph
            if self.pad_node == 1:
                batch_z_padding = batch_z[:, -1]
                batch_z = torch.cat([batch_temp_z, batch_z_padding.unsqueeze(1)], dim=1)
            elif self.pad_node > 1:
                batch_z_padding = torch.sum(batch_z[:, -self.pad_node:], dim=1, keepdim=False)
                batch_z = torch.cat([batch_temp_z, batch_z_padding.unsqueeze(1)], dim=1)
            else:
                batch_z = batch_temp_z

        # Resulting subgraph-level user representations: (B, T, z_dim)

        # --------------------------------------------------
        # 3. Local Cascade Structural Representation Learning
        # --------------------------------------------------
        # Extract graph-structural features from cascade subgraphs using BiGCN.
        batch_repretation = self.bigcn(batch_x, batch_l)  # (B, T, N_sub, feat_out)

        # Aggregate node-level graph features within each subgraph
        batch_repretation = torch.mean(batch_repretation, dim=2)  # (B, T, feat_out)

        # Combine local structural features with global user embeddings
        batch_repretation = torch.cat([batch_repretation, batch_z], dim=-1)  # (B, T, feat_out + z_dim)

        # --------------------------------------------------
        # 4. Joint Structural-Influence Representation Learning
        # --------------------------------------------------
        # Learn a joint representation of local cascade structure
        # and user-related information for each cascade subgraph.
        vae_loss_fusion, batch_z_repretation = self.ae(batch_repretation)

        # batch_z_repretation: (B, T, z_dim)
        # Joint structural-influence representation of each subgraph

        # --------------------------------------------------
        # 5. Temporal Representation Learning
        # --------------------------------------------------
        # Align temporal features with the corresponding cascade subgraphs.
        if self.increase_node > 1:
            batch_time_serise_subgs = batch_time_serise.squeeze(1)[:, self.increase_node - 1::self.increase_node]
            if self.pad_node != 0:
                batch_time_serise_subgs = torch.cat(
                    [batch_time_serise_subgs, batch_time_serise.squeeze(1)[:, -1].unsqueeze(-1)],
                    dim=-1
                )
            time_feature = batch_time_serise_subgs.unsqueeze(-1)  # (B, T, 1)
        else:
            time_feature = batch_time_serise.squeeze(1).unsqueeze(-1)  # (B, T, 1)

        # Concatenate structural-influence representations with temporal features
        z_fused_seq = batch_z_repretation                    # (B, T, z_dim)
        rnn_input = torch.cat([z_fused_seq, time_feature], dim=-1)  # (B, T, z_dim + 1)

        # Capture the temporal evolution of the cascade using BiGRU
        rnn_repretation, _ = self.biGRU(rnn_input)                # (B, T, 2*rnn_hidden)

        # --------------------------------------------------
        # 6. Structural-Influence-Aware Temporal Attention
        # --------------------------------------------------
        # Compute attention weights by jointly considering
        # BiGRU temporal states and structural-influence representations.
        # This enables the model to assign different importance
        # to cascade subgraphs based on both types of information.
        H_time, alpha = self.structural_influence_temporal_attention(rnn_repretation, z_fused_seq)  # H_time: (B, 2*rnn_hidden)

        # --------------------------------------------------
        # 7. Structural-Influence-Temporal Fusion
        # --------------------------------------------------
        # Obtain a global structural-influence representation
        # by aggregating the subgraph-level representations.
        u_global = torch.mean(z_fused_seq, dim=1)   # (B, z_dim)

        # Adaptively fuse the global structural-influence representation
        # with the attention-weighted temporal representation.
        graph_representation= self.structural_influence_temporal_fusion_gate(H_time, u_global)  # (B, D)

        # --------------------------------------------------
        # 8. Final Cascade Size Prediction
        # --------------------------------------------------
        # Predict the final cascade size from the fused representation.
        # pred = F.softplus(self.mlp2(graph_representation))
        pred = self.mlp2(graph_representation)      # (B, 1)

        # Compute the cascade size regression loss
        regression_loss = self.MeanSquaredLogarithmicError(pred, batch_y)

        # --------------------------------------------------
        # 9. Multi-Task Learning Objective
        # --------------------------------------------------
        # Combine the cascade size regression loss,
        # user classification loss, and autoencoder losses.
        total_loss = (
            regression_loss +
            total_classfier_loss +
            total_vae_loss_global +
            vae_loss_fusion
        )

        # Return the total loss, individual loss components,
        # classification accuracy, and cascade size prediction.
        return total_loss, total_classfier_loss, regression_loss, total_classfier_acc, pred